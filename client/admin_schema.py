from apps.schema.registry import registry
from apps.schema.base import AdminSchema, SchemaField
from .models import CustomUser, Payment
from .serializers import AdminCustomUserSerializer
from courses.serializers import AdminPaymentSerializer


@registry.register
class CustomUserSchema(AdminSchema):
    read_serializer_class = AdminCustomUserSerializer
    write_serializer_class = AdminCustomUserSerializer
    model    = CustomUser
    endpoint = "/api/customusers/"        # auto-generated by dynamic router
    exclude  = ["last_login"]
    # Override AbstractBaseUser.password's model metadata: admin writes are
    # accepted, but the serializer marks it write-only so it never appears in API reads.
    fields = [
        SchemaField(name="id", type="number", read_only=True, required=False),
        SchemaField(name="username", type="string", required=True, max_length=150),
        SchemaField(name="email", type="email", required=True),
        SchemaField(name="password", type="string", read_only=False, required=False),
        SchemaField(name="is_verified", type="boolean", required=False),
        SchemaField(name="is_active", type="boolean", required=False),
        SchemaField(name="is_staff", type="boolean", required=False),
    ]
    list_display = [
        "id", "username", "email",
        "is_verified", "is_active", "is_staff",
    ]
    search_fields = ["username", "email"]
    ordering      = ["-id"]


@registry.register
class PaymentSchema(AdminSchema):
    model    = Payment
    endpoint = "/data/payments/"          # AdminPaymentViewSet is here
    read_serializer_class = AdminPaymentSerializer
    list_display = [
        "id", "user", "course", "amount", "status", "created_at",
    ]
    search_fields = ["user__username", "course__title", "status"]
    ordering      = ["-created_at"]
    use_explicit_viewset = True
